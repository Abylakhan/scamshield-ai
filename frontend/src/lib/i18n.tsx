export const DICTS: Record<Lang, Dict> = { en, ru, kk };
export const LANG_LABELS: Record<Lang, string> = { kk: "Қаз", ru: "Рус", en: "Eng" };

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: Dict }
const I18nContext = createContext<Ctx | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("scamshield.lang");
    if (saved === "en" || saved === "ru" || saved === "kk") return saved;
  } catch { /* storage unavailable */ }
  const nav = navigator.language.slice(0, 2);
  return nav === "kk" ? "kk" : nav === "ru" ? "ru" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    try { localStorage.setItem("scamshield.lang", lang); } catch { /* ignore */ }
  }, [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t: DICTS[lang] }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}
